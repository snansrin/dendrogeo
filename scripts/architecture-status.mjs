#!/usr/bin/env node
import {readFileSync,writeFileSync} from 'node:fs';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {checkArchitecture} from './check-architecture.mjs';
import {checkDependencyRules} from './lib/dependency-rules.mjs';
import {collectRuntimeModules} from './lib/runtime-module-inventory.mjs';
import {scanServiceBoundaryDebt} from './check-service-boundaries.mjs';
import {findInlineEventAttributes} from './check-inline-events.mjs';
import {collectGeneratedMarkupHandlers} from './lib/generated-markup-handlers.mjs';

const ROOT=join(dirname(fileURLToPath(import.meta.url)),'..');
const OUTPUT=join(ROOT,'docs/ARCHITECTURE-STATUS.generated.md');
function measure(){
 const architecture=checkArchitecture(ROOT),dependencies=checkDependencyRules(ROOT),runtime=collectRuntimeModules(ROOT);
 const generatedHandlers=collectGeneratedMarkupHandlers(ROOT);
 const debt=Object.values(scanServiceBoundaryDebt(ROOT)).reduce((sum,row)=>sum+Object.values(row).reduce((n,value)=>n+value,0),0);
 const inlineEvents=findInlineEventAttributes(ROOT);
 return{architecture,dependencies,runtime,debt,inlineEvents,generatedHandlers};
}
export function renderArchitectureStatus(){
 const {architecture,dependencies,runtime,debt,inlineEvents,generatedHandlers}=measure();
 const ok=architecture.errors.length===0&&dependencies.errors.length===0&&debt===0&&inlineEvents.length===0;
 const initialScripts=runtime.initial.length;
 return `<!-- Generated by npm run architecture:status:write. Do not edit by hand. -->
# Mimari durum ölçümü

Bu dosya mimari kapılardan güncel sayıları üretir.

| Alan | Mevcut ölçüm | Durum |
|---|---:|---|
| JavaScript AST katman denetimi | ${architecture.checked} modül · ${architecture.errors.length} ihlal | ${architecture.errors.length?'Hata':'Geçti'} |
| AST bağımlılık yönü | ${dependencies.checked} modül · ${dependencies.errors.length} ihlal · ${dependencies.knownDebt.length} istisna | ${dependencies.errors.length?'Hata':'Geçti'} |
| Runtime envanteri | ${runtime.physical.length} fiziksel · ${runtime.initial.length} ilk yükleme · ${runtime.lazy.length} lazy · ${runtime.protected.size} SHA korumalı | Ölçüldü |
| Legacy servis sınır borcu | ${debt} DOM/Supabase/ağ erişimi | ${debt?'Açık':'Geçti; yeni ihlal kapalı'} |
| Statik HTML satır içi olay | ${inlineEvents.length} | ${inlineEvents.length?'Hata':'Geçti'} |
| Dinamik HTML olay borcu | ${generatedHandlers.total} nitelik · ${Object.keys(generatedHandlers.files).length} UI/service dosyası | ${generatedHandlers.total===0?'Tamamlandı':'Baseline ile sınırlı'}; yeni artış CI'da engellenir |
| İlk yükleme script bildirimi | ${initialScripts} modül | Sıra ve çevrimdışı manifesti açıkça korunuyor |

## Tamamlanan mimari kapıları

- Katman ve dependency kuralları AST ile doğrulanıyor; global facade sağlayıcıları ve bağımlılık yönü denetleniyor. Dinamik HTML inline handler borcu sıfır ve CI'da artışa kapalı.
- Servis katmanında DOM, Supabase ve ağ erişimi yok; sınır borcunun artması CI'ı durduruyor.
- Build, sürüm, CSP, Service Worker/lazy modül entegrasyonu, çekirdek hash ve HTML olay kapıları \`npm run check\` içinde.
- Tam test paketi, Chromium mobil iş akışları ve erişilebilirlik kontrolleri yerel release doğrulamasından geçti.

## Gelecek iyileştirmeler (kabul engeli değil)

- Lazy modül adaylarını gerçek kullanıcı oturumlarında ölç; yalnız kanıtlanan performans kazancı için yükleme davranışını değiştir.
- Klasik script sırasını değiştirmeden, el ile korunan HTML/Service Worker bildirimlerinin tek kaynaktan üretimi ayrı bir düşük riskli çalışma olarak değerlendirilebilir.
- Depo geneli biçim/lint politikası belirlenirse eski dosyaları topluca biçimlendirme; yalnız değişen modüllere aşamalı uygula.

**Kaynak mimarisi denetimi:** ${ok?'AST, dependency, servis sınırı ve markup kapıları geçti.':'Bir veya daha fazla mimari kapı başarısız; bu rapor release kabulü değildir.'}
`;
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const output=renderArchitectureStatus(),write=process.argv.includes('--write'),check=process.argv.includes('--check');
 if(write){writeFileSync(OUTPUT,output);console.log('✅ docs/ARCHITECTURE-STATUS.generated.md güncellendi.');}
 else if(check){
  if(readFileSync(OUTPUT,'utf8')!==output){console.error('🔴 Mimari durum raporu eski; npm run architecture:status:write çalıştırın.');process.exitCode=1;}
  else console.log('✅ Mimari durum raporu güncel.');
 }else process.stdout.write(output);
}
