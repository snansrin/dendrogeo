import{readFileSync,writeFileSync,existsSync}from'node:fs';
import{resolve}from'node:path';
import{evaluateTreeDataset}from'./lib/tree-detection-evaluation.mjs';
const [input,output]=process.argv.slice(2);
if(!input||!output)throw Error('Usage: node scripts/evaluate-tree-detection.mjs reference-and-predictions.json evaluation.json');
if(resolve(input)===resolve(output))throw Error('Output must not overwrite reference annotations.');
if(existsSync(output))throw Error('Output already exists; choose a new evaluation file.');
const bytes=readFileSync(input);if(bytes.length>20*1024*1024)throw Error('Input exceeds 20 MB.');
const result=evaluateTreeDataset(JSON.parse(bytes));writeFileSync(output,JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify({threshold:result.selectedThreshold,test:result.test,productionApproved:false}));
