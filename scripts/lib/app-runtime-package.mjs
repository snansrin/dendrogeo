/* Package classic module sources without merging their global lexical scopes. */
export const runtimePath='src/bootstrap/app-runtime.js';
export function packageApplication(html,readSource){
 const modules=[];
 const manifest=html.replace(/<script\s+src="(src\/[^"?]+\.js(?:\?[^" ]+)?)"([^>]*)><\/script>/g,(tag,url,attributes)=>{
  if(/\bdata-dg-eager\b/.test(attributes))return tag;
  modules.push([url,readSource(url.split('?')[0])]);
  return '<script src="'+url+'" type="application/x-dendrogeo-module"'+attributes+'></script>';
 });
 const runtime='"use strict";\n/* Generated by npm run build. Edit the source modules, not this artifact. */\n(function(){\n const modules='+JSON.stringify(modules)+';\n for(const [url,source] of modules){\n  const script=document.createElement("script");\n  script.textContent=source+"\\n//# sourceURL="+new URL(url,document.baseURI).href;\n  document.head.appendChild(script);\n  script.remove();\n }\n})();\n';
 return{manifest,runtime,count:modules.length};
}
