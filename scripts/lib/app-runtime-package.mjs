/* Package classic module sources without merging their global lexical scopes. */
import {createHash} from 'node:crypto';
export const runtimePath='src/bootstrap/app-runtime.js';
export function packageApplication(html,readSource){
 const modules=[];
 const manifest=html.replace(/<script\s+src="(src\/[^"?]+\.js(?:\?[^" ]+)?)"([^>]*)><\/script>/g,(tag,url,attributes)=>{
  if(/\bdata-dg-eager\b/.test(attributes))return tag;
  modules.push([url,readSource(url.split('?')[0])]);
  return '<script src="'+url+'" type="application/x-dendrogeo-module"'+attributes+'></script>';
 });
 // A relative diagnostic URL keeps each exact script body independent of the
 // deployment origin, so production and isolated fixtures share CSP hashes.
 const scriptHashes=modules.map(([url,source])=>"'sha256-"+createHash('sha256').update(source+'\n//# sourceURL='+url).digest('base64')+"'").join(' ');
 const runtime='"use strict";\n/* Generated by npm run build. Edit the source modules, not this artifact. */\n(function(){\n const modules='+JSON.stringify(modules)+';\n for(const [url,source] of modules){\n  const script=document.createElement("script");\n  script.textContent=source+"\\n//# sourceURL="+url;\n  document.head.appendChild(script);\n  script.remove();\n }\n})();\n';
 return{manifest:manifest.replace('__DG_SCRIPT_HASHES__',scriptHashes),runtime,count:modules.length};
}
